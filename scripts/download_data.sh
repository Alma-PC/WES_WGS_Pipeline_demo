#!/usr/bin/env bash
# =============================================================================
# Download the small public test dataset used by the demo pipeline.
#
#  1. Paired-end Illumina reads of GIAB HG001 (NA12878), restricted to a 500 kb
#     window of chr20 and subsampled, streamed directly from the indexed GIAB
#     BAM on the NCBI FTP (only the requested region is transferred).
#  2. Ensembl GRCh38 chromosome 20 FASTA.
#  3. Ensembl GRCh38 chromosome 20 GFF3 gene annotation (used by VEP offline).
#
# Origin and licence of every file: docs/DATA_SOURCES.md
# Requires: samtools, curl (both in environment.yml)
#
# Usage:  bash scripts/download_data.sh            # defaults below
#         FRACTION=0.05 bash scripts/download_data.sh
# =============================================================================
set -euo pipefail

# ---- Parameters (keep REGION in sync with config/config.yaml) ---------------
SAMPLE="${SAMPLE:-HG001}"
GIAB_BAM="${GIAB_BAM:-https://ftp-trace.ncbi.nlm.nih.gov/ReferenceSamples/giab/data/NA12878/NIST_NA12878_HG001_HiSeq_300x/NHGRI_Illumina300X_novoalign_bams/HG001.GRCh38_full_plus_hs38d1_analysis_set_minus_alts.300x.bam}"
# The source BAM uses UCSC-style names ("chr20"); the Ensembl reference uses "20".
REGION="${REGION:-chr20:33000000-33500000}"
# Source BAM is ~300x; 0.1 keeps ~30x. Seed 42 makes subsampling reproducible.
FRACTION="${FRACTION:-0.1}"
SEED="${SEED:-42}"
ENSEMBL_RELEASE="${ENSEMBL_RELEASE:-116}"
ENSEMBL="https://ftp.ensembl.org/pub/release-${ENSEMBL_RELEASE}"

RAW_DIR="data/raw"
REF_DIR="resources/reference"
ANN_DIR="resources/annotation"
mkdir -p "$RAW_DIR" "$REF_DIR" "$ANN_DIR"

log() { printf '[%s] %s\n' "$(date '+%H:%M:%S')" "$*"; }

download() {  # download <url> <dest>; skips files that already exist
  local url="$1" dest="$2"
  if [[ -s "$dest" ]]; then log "exists, skipping: $dest"; return; fi
  log "downloading $url"
  curl -fsSL --retry 3 --retry-delay 5 -o "${dest}.part" "$url"
  mv "${dest}.part" "$dest"
}

# ---- 1. Reads ---------------------------------------------------------------
R1="$RAW_DIR/${SAMPLE}_R1.fastq.gz"
R2="$RAW_DIR/${SAMPLE}_R2.fastq.gz"
if [[ -s "$R1" && -s "$R2" ]]; then
  log "exists, skipping: $R1 $R2"
else
  log "streaming $REGION from GIAB BAM (fraction=$FRACTION, seed=$SEED)"
  TMP_BAM="$RAW_DIR/.${SAMPLE}.region.bam"
  # -F 0x900: drop secondary/supplementary alignments so each read appears once.
  # samtools stores the remote .bai in the working directory; run it in RAW_DIR.
  # -s SEED.FRACTION (e.g. 42.1): read-name hashing keeps both mates together.
  ( cd "$RAW_DIR" && samtools view -b -F 0x900 -s "${SEED}${FRACTION#0}" \
      -o "$(basename "$TMP_BAM")" "$GIAB_BAM" "$REGION" )
  # Group mates together, then write properly paired reads only.
  samtools collate -u -O "$TMP_BAM" \
    | samtools fastq -n -1 "$R1" -2 "$R2" -0 /dev/null -s /dev/null -
  rm -f "$TMP_BAM" "$RAW_DIR"/*.bai
fi

# ---- 2. Reference -----------------------------------------------------------
download "$ENSEMBL/fasta/homo_sapiens/dna/Homo_sapiens.GRCh38.dna.chromosome.20.fa.gz" \
         "$REF_DIR/Homo_sapiens.GRCh38.dna.chromosome.20.fa.gz"

# ---- 3. Annotation ----------------------------------------------------------
download "$ENSEMBL/gff3/homo_sapiens/Homo_sapiens.GRCh38.${ENSEMBL_RELEASE}.chromosome.20.gff3.gz" \
         "$ANN_DIR/Homo_sapiens.GRCh38.${ENSEMBL_RELEASE}.chromosome.20.gff3.gz"

# ---- Provenance record ------------------------------------------------------
MANIFEST="data/MANIFEST.txt"
{
  echo "# Generated by scripts/download_data.sh on $(date -u '+%Y-%m-%dT%H:%M:%SZ')"
  echo "# See docs/DATA_SOURCES.md for origin and licences."
  echo "reads_source=$GIAB_BAM"
  echo "reads_region=$REGION"
  echo "reads_fraction=$FRACTION"
  echo "reads_seed=$SEED"
  echo "ensembl_release=$ENSEMBL_RELEASE"
  echo "samtools_version=$(samtools --version | head -n1)"
  echo "read_pairs=$(( $(gzip -dc "$R1" | wc -l) / 4 ))"
  echo
  echo "# md5 checksums"
  for f in "$R1" "$R2" "$REF_DIR"/*.fa.gz "$ANN_DIR"/*.gff3.gz; do
    if command -v md5sum >/dev/null; then md5sum "$f"; else md5 -r "$f"; fi
  done
} > "$MANIFEST"

log "done. Provenance written to $MANIFEST"
cat "$MANIFEST"
